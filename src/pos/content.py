def local_labour(r):
    rows = []
    tot = loc = 0
    for t, v in sorted(r.lg.trades_max.items(), key=lambda kv: -kv[1]):
        n = math.ceil(v)
        l_ = round(n * LOCAL_SHARE.get(t, 0.5))
        rows.append((t, n, l_, n - l_))
        tot += n
        loc += l_
    return rows, tot, loc


def site_dist(r):
    s, cr = r.site, r.crane
    R = cr["R_danger"]
    return {
        "south": s["y_crane"] - R,
        "north": s["H"] - (s["y_crane"] + R),
        "west": s["cr_x"][0] - R,
        "east": s["W"] - (s["cr_x"][1] + R),
        "house": 92.0 - (s["y_south"] + calc.TP["width_axes"]),
        "street": s["y_south"] + 2.5,
        "utilidor": s["sections"][0][0] + 7.0,
        "road_len": 2 * s["road_y"] + 155.0,
        "road_area": (2 * s["road_y"] + 155.0) * 3.5 + 120 * 2.5,
    }


