def vakhta_count(r):
    rows, tot, loc = local_labour(r)
    share = loc / tot
    st = r.staff["cat_max"]
    workers = st["Рабочие"]
    others = st["ИТР"] + st["Служащие"] + st["МОП и охрана"]
    v = round(workers * (1 - share) + others * (1 - ITR_LOCAL))
    return v, r.staff["N_all_max"] - v


